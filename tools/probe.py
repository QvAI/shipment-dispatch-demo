import argparse
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path


DB = Path(__file__).resolve().parents[1] / "db"


class PayloadConflict(Exception):
    pass


def marked_sql(source, name, *, required=True):
    match = re.search(rf"-- COURSE {name} BEGIN\s*(.*?)\s*-- COURSE {name} END", source, re.S)
    if not match:
        if required:
            raise ValueError(f"Missing {name} SQL markers in the package")
        return None
    sql = re.sub(r"^\s*(?:INTO |RETURNING ).*$", "", match[1], flags=re.M)
    sql = re.sub(r"\b(request_key|destination)_\b", r":\1", sql)
    return sql.strip().rstrip(";")


@contextmanager
def repository():
    """Run the marked package SQL against a disposable SQLite database."""
    connection = sqlite3.connect(":memory:")
    try:
        schema = (DB / "001_shipments.sql").read_text(encoding="utf-8")
        connection.executescript(schema.replace(" GENERATED BY DEFAULT AS IDENTITY", ""))
        for migration in sorted((DB / "migrations").glob("*.sql")):
            connection.executescript(migration.read_text(encoding="utf-8"))
        source = (DB / "shipment_api.pkb").read_text(encoding="utf-8")
        insert = marked_sql(source, "INSERT")
        replay = marked_sql(source, "REPLAY", required=False)
        raises_conflict = bool(re.search(r"RAISE_APPLICATION_ERROR\s*\(\s*-20\d{3}\b", source, re.I))

        def submit(request_key, destination):
            parameters = {"request_key": request_key, "destination": destination}
            try:
                with connection:
                    return connection.execute(insert, parameters).lastrowid
            except sqlite3.IntegrityError as error:
                if not replay or error.sqlite_errorcode != sqlite3.SQLITE_CONSTRAINT_UNIQUE:
                    raise
                existing = connection.execute(replay, parameters).fetchone()
                if existing is None:
                    raise
                shipment_id, saved_destination = existing
                if saved_destination != destination:
                    if not raises_conflict:
                        raise AssertionError(
                            "Missing RAISE_APPLICATION_ERROR in db/shipment_api.pkb for payload mismatch"
                        ) from error
                    raise PayloadConflict(request_key) from error
                return shipment_id

        def row_count():
            return connection.execute("SELECT COUNT(*) FROM shipments").fetchone()[0]

        yield submit, row_count
    finally:
        connection.close()


def show(label, passed, evidence):
    print(f"{'PASS' if passed else 'FAIL'} {label}: {evidence}")
    return passed


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--single", action="store_true", help="Run only the happy path")
    args = parser.parse_args()
    print("LOCAL SQL / SQLite fixture (no Oracle execution)")

    with repository() as (submit, rows):
        first = submit("REQ-101", "DEB")
        passed = show("FIRST", rows() == 1, f"id={first}, rows={rows()}")
        if args.single:
            return int(not passed)
        repeated = submit("REQ-101", "DEB")
        passed &= show("REPLAY", repeated == first and rows() == 1,
                       f"first={first}, second={repeated}, rows={rows()} (expected: same ID, one row)")

    with repository() as (submit, rows):
        first = submit("REQ-101", "DEB")
        other = submit("REQ-102", "DEB")
        passed &= show("NEW KEY", other != first and rows() == 2,
                       f"first={first}, second={other}, rows={rows()}")

    with repository() as (submit, rows):
        submit("REQ-101", "DEB")
        try:
            submit("REQ-101", "BUD")
        except PayloadConflict:
            rejected = True
        else:
            rejected = False
        passed &= show("MISMATCH", rejected and rows() == 1,
                       f"rejected={rejected}, rows={rows()} (expected: rejected, one row)")
    return int(not passed)


if __name__ == "__main__":
    raise SystemExit(main())
